#!/usr/bin/env python3
"""Build the theme files from content/themes.json.

A theme is a set of values for the --ah-* tokens at the top of site.css, plus an optional block of extra
rules. `python3 tools/build_themes.py` writes the themes block at the end of site.css, and theme.js. `--check` fails if they are stale.

The default theme is the one every visitor to arithim.com sees. Any other theme can be previewed on a
non-production host with ?theme=<name> (the choice is remembered and a small picker appears), and it goes
live only when "default" in content/themes.json is changed and merged.
"""
from __future__ import annotations

import hashlib
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
DATA = ROOT / "content" / "themes.json"


def token_block() -> str:
    css = (ROOT / "site.css").read_text(encoding="utf-8")
    return css[css.index("ah-tokens:start"):css.index("ah-tokens:end")]


def theme_css(name: str, theme: dict) -> str:
    block = token_block()
    toks = theme.get("tokens", {})
    rgb = theme.get("rgb", {})
    lines = [f"/* Theme: {theme['label']}. Generated by tools/build_themes.py from content/themes.json. */", f'html[data-theme="{name}"] {{']
    for token, value in toks.items():
        lines.append(f"  --ah-{token}: {value};")
    for m in re.finditer(r"--ah-([a-z-]+)-(\d\d):\s*rgba\((\d+),(\d+),(\d+),([0-9.]+)\);", block):
        base, alpha = m.group(1), m.group(6)
        if base in rgb:
            r, g, b = rgb[base]
            lines.append(f"  --ah-{base}-{m.group(2)}: rgba({r},{g},{b},{alpha});")
    lines.append("}")
    if theme.get("css"):
        lines.append(theme["css"])
    return "\n".join(lines) + "\n"


THEMES_START = "/* ah-themes:start (generated by tools/build_themes.py from content/themes.json; do not edit) */"
THEMES_END = "/* ah-themes:end */"


def themes_block(data: dict) -> str:
    parts = [THEMES_START]
    for name, t in data["themes"].items():
        if t.get("tokens"):
            parts.append(theme_css(name, t).rstrip("\n"))
    parts.append(THEMES_END)
    return "\n".join(parts)


def theme_js(data: dict) -> str:
    labels = {n: t["label"] for n, t in data["themes"].items()}
    modes = {n: t.get("mode", "dark") for n, t in data["themes"].items()}
    public = [n for n, t in data["themes"].items() if t.get("public")]
    return f"""/* Theme loader. Generated by tools/build_themes.py from content/themes.json.
   The themes themselves are in site.css. Visitors can switch between the public themes with the button in the
   header, and the choice is remembered. Draft themes can be previewed on any host that is not arithim.com with
   ?theme=<name>, and a picker for all themes appears there. */
(function () {{
  var DEFAULT = {json.dumps(data['default'])};
  var LABELS = {json.dumps(labels)};
  var MODES = {json.dumps(modes)};
  var PUBLIC = {json.dumps(public)};
  var root = document.documentElement;
  var prod = /(^|\\.)arithim\\.com$/.test(location.hostname);
  var ok = function (n) {{ return LABELS.hasOwnProperty(n) && (!prod || PUBLIC.indexOf(n) > -1); }};
  var name = DEFAULT;
  var save = function (n) {{ try {{ localStorage.setItem('ah-theme', n); }} catch (e) {{}} }};
  try {{
    var q = new URLSearchParams(location.search).get('theme');
    if (q && ok(q)) save(q);
    var saved = localStorage.getItem('ah-theme');
    if (saved && ok(saved)) name = saved;
  }} catch (e) {{}}
  var apply = function (n) {{ name = n; root.setAttribute('data-theme', n); root.setAttribute('data-mode', MODES[n] || 'dark'); }};
  apply(name);
  document.addEventListener('DOMContentLoaded', function () {{
    var next = function () {{ var i = PUBLIC.indexOf(name); return PUBLIC[(i + 1) % PUBLIC.length]; }};
    var label = function () {{ var l = 'Switch to the ' + (MODES[next()] || 'dark') + ' theme'; [].slice.call(document.querySelectorAll('[data-theme-toggle]')).forEach(function (b) {{ b.setAttribute('aria-label', l); b.setAttribute('title', l); }}); }};
    document.addEventListener('click', function (e) {{ var b = e.target.closest && e.target.closest('[data-theme-toggle]'); if (!b) return; var n = next(); apply(n); save(n); label(); var s = document.querySelector('.ah-theme-picker select'); if (s) s.value = n; }});
    label(); setTimeout(label, 600); window.addEventListener('load', function () {{ setTimeout(label, 300); }});
    if (prod) return;
    var box = document.createElement('label'); box.className = 'ah-theme-picker'; box.textContent = 'Theme ';
    var sel = document.createElement('select');
    Object.keys(LABELS).forEach(function (n) {{ var o = document.createElement('option'); o.value = n; o.textContent = LABELS[n]; if (n === name) o.selected = true; sel.appendChild(o); }});
    sel.onchange = function () {{ apply(sel.value); save(sel.value); label(); }};
    box.appendChild(sel);
    document.body.appendChild(box);
  }});
}})();
"""


def main():
    data = json.loads(DATA.read_text(encoding="utf-8"))
    css_path = ROOT / "site.css"
    css = css_path.read_text(encoding="utf-8")
    block = themes_block(data)
    rx = re.compile(re.escape(THEMES_START) + r".*?" + re.escape(THEMES_END), re.S)
    new_css = rx.sub(lambda _: block, css) if rx.search(css) else css.rstrip("\n") + "\n\n" + block + "\n"
    js = theme_js(data)
    version = hashlib.sha1(js.encode()).hexdigest()[:8]  # the head partial links theme.js?v=<hash>, so a changed script is never served from cache
    head = ROOT / "tools" / "partials" / "head.html"
    head_text = re.sub(r'/theme\.js(\?v=[0-9a-f]+)?"', f'/theme.js?v={version}"', head.read_text(encoding="utf-8"))
    outputs = {css_path: new_css, ROOT / "theme.js": js, head: head_text}
    stale = []
    for path, content in outputs.items():
        if not path.exists() or path.read_text(encoding="utf-8") != content:
            stale.append(path.name)
            if "--check" not in sys.argv:
                path.write_text(content, encoding="utf-8")
    if "--check" in sys.argv:
        print("ok: theme files are up to date" if not stale else "stale: " + ", ".join(stale))
        sys.exit(1 if stale else 0)
    print("wrote: " + ", ".join(stale) if stale else "nothing to change")


if __name__ == "__main__":
    main()
